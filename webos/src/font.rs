/// The width of `text` drawn at `scale`.
pub fn width(text: &str, scale: i32) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 { 0 } else { (n * (W + GAP) - GAP) * scale }
}

/// Calls `rect(x, y, w, h)` for each lit pixel of `text` with its top left at `(x, y)`.
pub fn draw(text: &str, x: i32, y: i32, scale: i32, mut rect: impl FnMut(i32, i32, i32, i32)) {
    for (i, c) in text.chars().enumerate() {
        let gx = x + i as i32 * (W + GAP) * scale;
        for (row, bits) in glyph(c).into_iter().enumerate() {
            // Runs of lit pixels in a row are one rectangle.
            let mut col = 0;
            while col < W {
                if bits >> (W - 1 - col) & 1 == 0 {
                    col += 1;
                    continue;
                }
                let start = col;
                while col < W && bits >> (W - 1 - col) & 1 == 1 {
                    col += 1;
                }
                rect(gx + start * scale, y + row as i32 * scale, (col - start) * scale, scale);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn draws_runs_not_pixels() {
        let mut rects = Vec::new();
        draw("I", 10, 20, 2, |x, y, w, h| rects.push((x, y, w, h)));
        // "I" is a bar, a stem of one pixel and a bar: 1 + 5 + 1 rectangles.
        assert_eq!(rects.len(), 7);
        assert_eq!(rects[0], (10 + 2, 20, 6, 2));
        assert_eq!(width("AB", 3), (2 * 6 - 1) * 3);
        assert_eq!(width("", 3), 0);
    }

    #[test]
    fn typographic_apostrophes_are_drawn() {
        assert_eq!(glyph('\u{2019}'), glyph('\''));
        assert_ne!(glyph('\u{2019}'), glyph('\u{1F600}'));
    }

    #[test]
    fn lower_case_is_drawn_as_capitals() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_ne!(glyph('a'), glyph('b'));
    }
}
