//! A 5×7 bitmap font for the app's screens (the TV gives us no text drawing). Upper case only:
//! lower case letters are drawn as capitals.

/// Width of a glyph in font pixels (it is 7 high), and the gap after it.
pub const W: i32 = 5;
pub const GAP: i32 = 1;

